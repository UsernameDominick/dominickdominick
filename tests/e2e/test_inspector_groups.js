const E2E_BASE = process.env.E2E_BASE || "http://localhost:8787";
const { chromium } = require("./_pw.cjs");
(async () => {
  const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
  const ctx = await b.newContext({ storageState: process.env.ADMIN_STATE, viewport: { width: 1440, height: 900 } });
  const p = await ctx.newPage();
  const errs = []; p.on("pageerror", (e) => errs.push(String(e))); p.on("dialog", (d) => d.accept());
  let fails = 0; const ok = (c, m) => { console.log((c ? "PASS" : "FAIL") + " — " + m); if (!c) fails++; };
  await p.goto((E2E_BASE + "/admin/"), { waitUntil: "networkidle" });
  await p.waitForSelector("#app:not([hidden])");
  await p.waitForTimeout(500);
  const blk = p.locator("#canvas .admin-block").nth(1);
  const bb = await blk.boundingBox();
  await p.mouse.click(bb.x + 20, bb.y + 20);
  await p.waitForTimeout(500);
  const blockId = await blk.getAttribute("data-id") || await blk.getAttribute("data-block-id");
  ok(await p.locator("#inspector-style-fields .style-group").count() === 7, "7 style groups");
  ok(!(await p.isVisible('#inspector-style-fields [data-key="padding"]')), "Box starts collapsed");
  await p.click('#inspector-style-fields .style-group[data-group="box"] > summary');
  await p.fill('#inspector-style-fields [data-key="padding"]', "12");
  await p.press('#inspector-style-fields [data-key="padding"]', "Tab");
  await p.waitForTimeout(700);
  ok(await p.isVisible('#inspector-style-fields [data-key="padding"]'), "Box stays open after re-render");
  ok((await p.textContent('.style-group[data-group="box"] .style-group-count').catch(() => "")) === "1 set", "summary shows 1 set");
  // color
  await p.click('#inspector-style-fields .style-group[data-group="text"] > summary').catch(() => {});
  await p.evaluate(() => { const i = document.querySelector('#inspector-style-fields [data-key="color"]'); i.value = "#ff0000"; i.dispatchEvent(new Event("change", { bubbles: true })); });
  await p.waitForTimeout(700);
  ok(/#ff0000/i.test(await p.textContent('.style-group[data-group="text"] .color-field') || ""), "set color shows its hex");
  // revert
  await p.fill('#inspector-style-fields [data-key="padding"]', "");
  await p.press('#inspector-style-fields [data-key="padding"]', "Tab");
  await p.waitForTimeout(600);
  await p.click('.style-group[data-group="text"] .clear-color');
  await p.waitForTimeout(700);
  ok(!(await p.$('.style-group .style-group-count')), "reverted: no groups report values");
  ok(errs.length === 0, "no page errors " + errs.join(";"));
  console.log(fails ? `${fails} FAILED` : "ALL PASS");
  await b.close();
})();
