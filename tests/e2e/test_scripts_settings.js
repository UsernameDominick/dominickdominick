// A script that changes one setting must leave the others alone (the site's settings save clears every key it is not given).
const E2E_BASE = process.env.E2E_BASE || "http://localhost:8787";
const { chromium, request } = require("./_pw.cjs");
const B = E2E_BASE + "/api/admin";
(async () => {
  const api = await request.newContext({ storageState: process.env.ADMIN_STATE });
  const b = await chromium.launch();
  const ctx = await b.newContext({ storageState: process.env.ADMIN_STATE, viewport: { width: 1440, height: 900 } });
  const p = await ctx.newPage();
  const errs = []; p.on("pageerror", (e) => errs.push(String(e))); p.on("dialog", (d) => d.accept());
  let fails = 0; const ok = (c, m, x) => { console.log((c ? "PASS" : "FAIL") + " — " + m + (x !== undefined && !c ? " " + JSON.stringify(x) : "")); if (!c) fails++; };
  const settings = async () => (await api.get(B + "/settings")).json();
  const before = await settings();
  await api.put(B + "/settings", { data: { ...before, theme_bg: "#101010", theme_accent: "#ff7a45", site_brand: "QQ brand", empty_search_text: "QQ nothing here" } });
  const seeded = await settings();
  ok(seeded.theme_bg === "#101010" && seeded.empty_search_text === "QQ nothing here", "fixture settings are in place");

  await p.goto(E2E_BASE + "/admin/", { waitUntil: "networkidle" });
  await p.waitForSelector("#app:not([hidden])");
  await p.click("#scripts-btn");
  await p.waitForSelector("#scripts-modal:not([hidden])");
  await p.fill(".ce-input", 'await site.settings.update({ theme_accent: "#123456" });\nawait site.put("/settings", { empty_search_text: "QQ changed" });');
  await p.click("#script-run");
  await p.waitForFunction(() => /Preview finished/.test(document.getElementById("script-status").textContent), null, { timeout: 8000 });
  const mid = await settings();
  ok(mid.theme_accent === "#ff7a45" && mid.empty_search_text === "QQ nothing here", "a preview changes nothing");
  const lines = await p.$$eval("#script-changes li", (l) => l.map((x) => x.textContent));
  ok(lines.length === 2 && /PUT \/settings \(theme_accent\)/.test(lines[0]), "the change list names only the setting the script asked for", lines);
  await p.click("#script-apply");
  await p.waitForSelector("#script-confirm:not([hidden])");
  await p.click("#script-confirm-go");
  await p.waitForFunction(() => /Applied/.test(document.getElementById("script-status").textContent), null, { timeout: 8000 });
  const after = await settings();
  ok(after.theme_accent === "#123456" && after.empty_search_text === "QQ changed", "the named settings changed", { a: after.theme_accent, e: after.empty_search_text });
  ok(after.theme_bg === "#101010" && after.site_brand === seeded.site_brand, "and the others were left alone", { bg: after.theme_bg, brand: after.site_brand });
  const lost = Object.keys(seeded).filter((k) => seeded[k] && !after[k]);
  ok(lost.length === 0, "no setting that had a value was cleared", lost);
  ok(errs.length === 0, "no page errors", errs);
  await api.put(B + "/settings", { data: before });
  console.log(fails ? `${fails} FAILED` : "ALL PASS");
  await b.close();
})();
