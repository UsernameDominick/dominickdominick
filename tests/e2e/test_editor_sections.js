const E2E_BASE = process.env.E2E_BASE || "http://localhost:8787";
const { chromium } = require("./_pw.cjs");
(async () => {
  const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
  const ctx = await b.newContext({ storageState: process.env.ADMIN_STATE, viewport: { width: 1440, height: 900 } });
  const p = await ctx.newPage();
  const errs = []; p.on("pageerror", (e) => errs.push(String(e))); p.on("dialog", (d) => d.accept());
  let fails = 0; const ok = (c, m) => { console.log((c ? "PASS" : "FAIL") + " — " + m); if (!c) fails++; };
  await p.goto((E2E_BASE + "/admin/"), { waitUntil: "networkidle" });
  await p.waitForSelector("#app:not([hidden])");
  await p.evaluate(() => document.getElementById("articles-btn").click());
  await p.waitForTimeout(700);
  await p.click("#articles-list .article-row >> nth=0").catch(async () => { await p.evaluate(() => document.querySelector("#articles-list [data-id]").click()); });
  await p.waitForTimeout(700);
  const title = await p.inputValue("#article-title");
  ok(!!title, "article loaded: " + title);
  ok(!(await p.isVisible("#article-canonical-url")), "SEO field starts collapsed");
  await p.click('#articles-modal summary:has-text("Sharing")');
  ok(await p.isVisible("#article-canonical-url"), "section expands on click");
  const orig = await p.inputValue("#article-canonical-url");
  await p.fill("#article-canonical-url", "https://dominickdominick.com/test-canonical");
  await p.click("#save-article");
  await p.waitForTimeout(900);
  const list = await (await p.request.get((E2E_BASE + "/api/admin/articles"))).json();
  const art = (Array.isArray(list) ? list : list.articles || []).find((a) => a.title === title);
  let full = art;
  if (art && art.canonical_url === undefined) full = await (await p.request.get(`${E2E_BASE}/api/admin/articles/${art.id}`)).json();
  ok(full && full.canonical_url === "https://dominickdominick.com/test-canonical", "value inside collapsed-by-default section saved");
  await p.fill("#article-canonical-url", orig);
  await p.click("#save-article");
  await p.waitForTimeout(900);
  ok(await p.isVisible("#save-article"), "sticky Save visible");
  ok(errs.length === 0, "no page errors " + errs.join(";"));
  console.log(fails ? `${fails} FAILED` : "ALL PASS");
  await b.close();
})();
