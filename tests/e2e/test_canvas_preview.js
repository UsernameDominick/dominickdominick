const E2E_BASE = process.env.E2E_BASE || "http://localhost:8787";
const { chromium, request } = require("./_pw.cjs");
(async () => {
  let fail = 0; const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) fail++; };
  const c = await request.newContext({ storageState: process.env.ADMIN_STATE });
  const f = (m, p, b) => c.fetch((E2E_BASE + "/api/admin") + p, { method: m, data: b });
  const pg = await (await f("POST", "/pages", { title: "QQ Canvas Page", slug: "qq-canvas-page" })).json();
  const add = (type, content, col, row, cs = 8, rs = 3) => f("POST", `/pages/${pg.id}/blocks`, { type, content, col, row, col_span: cs, row_span: rs });
  await add("heading", { text: "QQ <b>Heading</b>", level: 2 }, 0, 0);
  await add("text", { text: "QQ body text that goes on for a while to test the clamp." }, 8, 0);
  await add("button", { label: "QQ Go", url: "/x" }, 16, 0);
  await add("quote", { text: "QQ quote" }, 0, 3);
  await add("divider", {}, 8, 3, 8, 1);
  await add("heading", { text: "QQ Small Heading", level: 2 }, 0, 7, 6, 1);
  await add("button", { label: "QQ Edge", url: "/x" }, 21, 7, 4, 1);
  await add("gallery", { images: ["/media/qq-none.png", { url: "/media/qq-none2.png", alt: "" }] }, 16, 3);
  const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, storageState: process.env.ADMIN_STATE });
  const p = await ctx.newPage(); const errs = []; p.on("pageerror", (e) => errs.push(e.message)); p.on("dialog", (d) => d.accept());
  await p.goto((E2E_BASE + "/admin/")); await p.waitForSelector("#app:not([hidden])");
  await p.selectOption("#page-picker", String(pg.id)); await p.waitForSelector("#canvas .admin-block");
  await p.waitForTimeout(500);
  const r = await p.evaluate(() => ({ n: document.querySelectorAll("#canvas .admin-block").length, cls: ["pv-heading", "pv-text", "pv-button", "pv-quote", "pv-divider", "pv-gallery"].filter((k) => document.querySelector("." + k)), xss: document.querySelectorAll("#canvas .pv-heading b").length, gimgs: document.querySelectorAll(".pv-gallery img").length }));
  ok(r.n === 8 && r.cls.length === 6, `six blocks with preview classes ${r.cls}`);
  ok(r.xss === 0, "heading markup escaped");
  ok(r.gimgs === 2, "gallery handles string and object entries");
  ok(await p.locator(".canvas-toolbar").count() === 0, "no toolbar before selection");
  const blk = p.locator("#canvas .admin-block").first(); const bb = await blk.boundingBox();
  await p.mouse.click(bb.x + 30, bb.y + 30); await p.waitForTimeout(500);
  ok(await p.locator(".canvas-toolbar").count() === 1, "toolbar appears for selected block");
  const labels = await p.$$eval(".canvas-toolbar button", (x) => x.map((y) => y.textContent));
  ok(labels.join() === "Edit,Copy,Duplicate,Lock,Fit,Delete", `toolbar buttons ${labels}`);
  ok(await p.evaluate(() => { const bar = document.querySelector(".canvas-toolbar"); return bar.previousElementSibling && bar.previousElementSibling.classList.contains("selected"); }), "toolbar sits right after the selected block in DOM order");
  await p.click(".canvas-toolbar button:has-text('Duplicate')"); await p.waitForTimeout(800);
  ok((await p.locator("#canvas .admin-block").count()) === 9, "Duplicate via toolbar adds a block");
  await p.screenshot({ path: `${require("os").tmpdir()}/canvas_preview.png` });
  await p.click(".canvas-toolbar button:has-text('Lock')"); await p.waitForTimeout(800);
  ok(await p.evaluate(() => document.activeElement && document.activeElement.closest(".canvas-toolbar") !== null && document.activeElement.textContent === "Unlock"), "focus returns to the toolbar button after Lock");
  ok(await p.evaluate(() => document.querySelector(".canvas-toolbar .canvas-toolbar-danger").disabled), "Delete disabled while locked");
  ok(await p.locator(".canvas-toolbar button:has-text('Unlock')").count() === 1, "Lock toggles to Unlock");
  await p.click(".canvas-toolbar button:has-text('Unlock')"); await p.waitForTimeout(600);
  await p.click(".canvas-toolbar button:has-text('Delete')"); await p.waitForTimeout(900);
  ok((await p.locator("#canvas .admin-block").count()) === 8, "Delete via toolbar removes it");
  await p.keyboard.press("Escape"); await p.waitForTimeout(300);
  ok(await p.locator(".canvas-toolbar").count() === 0, "Escape clears the toolbar");
  // edge block: toolbar stays inside the canvas
  const eb = await p.locator("#canvas .admin-block", { hasText: "QQ Edge" }).boundingBox();
  await p.mouse.click(eb.x + 10, eb.y + 10); await p.waitForTimeout(500);
  ok(await p.evaluate(() => { const c = document.getElementById("canvas").getBoundingClientRect(); const t = document.querySelector(".canvas-toolbar").getBoundingClientRect(); return t.right <= c.right + 1 && t.left >= c.left - 1; }), "toolbar clamped inside the canvas at the right edge");
  // small block preview not clipped
  ok(await p.evaluate(() => { const d = [...document.querySelectorAll("#canvas .admin-block")].find((x) => /QQ Small Heading/.test(x.textContent)); const h = d.querySelector(".pv-heading").getBoundingClientRect(), r = d.getBoundingClientRect(); return h.bottom <= r.bottom + 0.5 && h.top >= r.top - 0.5 && d.classList.contains("admin-block-compact"); }), "small block heading preview fully visible");
  // click empty canvas clears toolbar
  const cb = await p.locator("#canvas").boundingBox();
  await p.mouse.click(cb.x + cb.width - 6, cb.y + 420); await p.waitForTimeout(400);
  ok(await p.locator(".canvas-toolbar").count() === 0, "clicking empty canvas removes the toolbar");
  ok(errs.length === 0, `no errors ${errs}`);
  await f("DELETE", `/pages/${pg.id}`); await f("DELETE", `/pages/${pg.id}/permanent`);
  await b.close(); process.exit(fail ? 1 : 0);
})();
