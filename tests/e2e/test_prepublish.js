const E2E_BASE = process.env.E2E_BASE || "http://localhost:8787";
const { chromium } = require("./_pw.cjs");
const AxeBuilder = (() => { try { return require("@axe-core/playwright").default || require("@axe-core/playwright").AxeBuilder; } catch { return null; } })();
(async () => {
  const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
  const ctx = await b.newContext({ storageState: process.env.ADMIN_STATE, viewport: { width: 1440, height: 900 } });
  const p = await ctx.newPage();
  const errs = []; p.on("pageerror", (e) => errs.push(String(e))); p.on("dialog", (d) => d.accept());
  let fails = 0; const ok = (c, m) => { console.log((c ? "PASS" : "FAIL") + " — " + m); if (!c) fails++; };
  const api = (path) => p.request.get((E2E_BASE + "/api/admin/") + path).then((r) => r.json());
  const find = async (slugPart) => { const l = await api("articles"); return (Array.isArray(l) ? l : l.articles || []).find((a) => a.title === slugPart); };
  await p.goto((E2E_BASE + "/admin/"), { waitUntil: "networkidle" });
  await p.waitForSelector("#app:not([hidden])");
  await p.evaluate(() => document.getElementById("articles-btn").click());
  await p.waitForTimeout(600);
  await p.click("#new-article"); await p.waitForTimeout(300);
  const T = "QQ prepublish check";
  await p.fill("#article-title", T);
  await p.fill("#article-body", "Short body that is still long enough for the server to accept it.");
  await p.check("#article-published");
  await p.click("#save-article");
  await p.waitForSelector("#prepublish-modal:not([hidden])", { timeout: 3000 }).catch(() => {});
  ok(await p.isVisible("#prepublish-modal"), "checklist appears when publishing a thin article");
  const items = await p.$$eval("#prepublish-list li", (n) => n.length);
  ok(items >= 3, "lists several things: " + items);
  if (AxeBuilder) { const r = await new AxeBuilder({ page: p }).include("#prepublish-modal").analyze(); ok(r.violations.length === 0, "axe clean " + r.violations.map((v) => v.id)); }
  await p.keyboard.press("Escape");
  await p.waitForTimeout(500);
  ok(!(await p.isVisible("#prepublish-modal")), "Esc closes it");
  ok(!(await find(T)), "going back saved nothing");
  await p.click("#save-article");
  await p.waitForSelector("#prepublish-modal:not([hidden])");
  await p.click("#prepublish-back"); await p.waitForTimeout(400);
  ok(!(await find(T)), "Go back saved nothing");
  await p.setViewportSize({ width: 375, height: 700 });
  await p.click("#save-article");
  await p.waitForSelector("#prepublish-modal:not([hidden])");
  const overflow = await p.evaluate(() => { const m = document.querySelector("#prepublish-modal .modal-content, #prepublish-modal > div"); return m ? m.scrollWidth > m.clientWidth + 1 : false; });
  ok(!overflow, "no horizontal overflow on phone");
  await p.setViewportSize({ width: 1440, height: 900 });
  await p.click("#prepublish-go"); await p.waitForTimeout(1200);
  const a = await find(T);
  ok(a && a.published_at, "Publish anyway publishes");
  // already live -> no modal
  await p.fill("#article-body", "Short body that is still long enough for the server, edited now.");
  await p.click("#save-article"); await p.waitForTimeout(900);
  ok(!(await p.isVisible("#prepublish-modal")), "already-published article saves without the checklist");
  // draft with Published ticked: autosave must not publish
  await p.click("#new-article"); await p.waitForTimeout(300);
  const T2 = "QQ prepublish autosave";
  await p.fill("#article-title", T2); await p.fill("#article-body", "Draft text");
  await p.check("#article-published");
  await p.waitForTimeout(3500);
  const d = await find(T2);
  ok(!d || !d.published_at, "autosave leaves a ticked-but-unsaved draft unpublished");
  ok(errs.length === 0, "no page errors " + errs.join(";"));
  for (const t of [T, T2]) { const x = await find(t); if (x) await p.request.delete((E2E_BASE + "/api/admin/articles/") + x.id); }
  console.log(fails ? `${fails} FAILED` : "ALL PASS");
  await b.close();
})();
