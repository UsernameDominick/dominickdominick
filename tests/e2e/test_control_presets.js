const E2E_BASE = process.env.E2E_BASE || "http://localhost:8787";
const { chromium } = require("./_pw.cjs");
(async () => {
  const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
  const ctx = await b.newContext({ storageState: process.env.ADMIN_STATE, viewport: { width: 1440, height: 900 } });
  const p = await ctx.newPage();
  const errs = []; p.on("pageerror", (e) => errs.push(String(e)));
  let fails = 0; const ok = (c, m) => { console.log((c ? "PASS" : "FAIL") + " — " + m); if (!c) fails++; };
  await p.goto((E2E_BASE + "/admin/"), { waitUntil: "networkidle" });
  await p.waitForSelector("#app:not([hidden])");
  const rad = () => p.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue("--control-radius").trim());
  ok((await rad()) === "999px", "default admin control radius is pill");
  await p.evaluate(() => document.getElementById("site-settings-btn").click());
  await p.waitForTimeout(500);
  ok(await p.getAttribute('.control-preset[data-setting="control_shape"] button[data-value="pill"]', "aria-pressed") === "true", "unsaved shape shows Pill pressed");
  await p.click('.control-preset[data-setting="control_shape"] button[data-value="soft"]');
  const prev = await p.evaluate(() => getComputedStyle(document.querySelector("#control-preview .btn")).borderTopLeftRadius);
  ok(prev === "6px", "preview updates live (" + prev + ")");
  ok((await rad()) === "999px", "admin not changed before save");
  await p.click("#save-settings");
  await p.waitForTimeout(800);
  ok((await rad()) === "6px", "admin applies saved shape after save");
  const html = await (await p.request.get((E2E_BASE + "/"))).text();
  ok(html.includes("--control-radius:6px"), "public page emits saved shape");
  await p.reload({ waitUntil: "networkidle" });
  await p.waitForTimeout(500);
  ok((await rad()) === "6px", "admin applies saved shape on boot");
  await p.evaluate(() => document.documentElement.setAttribute("data-theme", "light"));
  const lightBg = await p.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue("--bg").trim());
  ok(lightBg !== "#0b0b0c", "light theme keeps its own background (" + lightBg + ")");
  await p.evaluate(() => document.documentElement.removeAttribute("data-theme"));
  // restore
  await p.evaluate(() => document.getElementById("site-settings-btn").click());
  await p.waitForTimeout(500);
  await p.click('.control-preset[data-setting="control_shape"] button[data-value="pill"]');
  await p.click("#save-settings");
  await p.waitForTimeout(800);
  ok((await rad()) === "999px", "restored to pill");
  ok(errs.length === 0, "no page errors " + errs.join(";"));
  console.log(fails ? `${fails} FAILED` : "ALL PASS");
  await b.close();
})();
