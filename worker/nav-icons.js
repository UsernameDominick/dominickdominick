// The art becomes one path of unit squares, a run of ink on a row at a time.
function pathOf(rows) {
  let d = "";
  rows.forEach((row, y) => {
    const runs = row.matchAll(/#+/g);
    for (const m of runs) d += `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`;
  });
  return `<path d="${d}"/>`;
}

const P = Object.fromEntries(Object.entries(ART).map(([name, rows]) => [name, pathOf(rows)]));

// First match wins, so the more specific words come first.
const RULES = [
  ["notes", /hidden|private|vault|secret/],
  ["home", /^home$|^index$|^start$/],
  ["trainer", /train|aim|fps|shoot|target/],
  ["studio", /studio|music|song|beat|audio/],
  ["random", /random|shuffle|surprise/],
  ["articles", /article|blog|writ|post|journal|essay|news/],
  ["projects", /project|work|portfolio|build/],
  ["components", /component|part|lab|tool|kit/],
  ["topics", /topic|tag|categor|subject/],
  ["circuit", /circuit|sim|electr/],
  ["scans", /scan|3d|model/],
  ["photos", /photo|gallery|image|picture|^pic/],
  ["contact", /contact|message|chat|mail|hello/],
  ["about", /about|bio|^me$|who/],
  ["resume", /resume|cv|experience/],
  ["search", /search|find/],
  ["saved", /saved|bookmark|later/],
  ["history", /history|recent/],
  ["notes", /note/],
];

export function navIconName(slug, label) {
  const s = String(slug || "").toLowerCase();
  const l = String(label || "").toLowerCase();
  for (const [name, re] of RULES) if (re.test(s)) return name;
  for (const [name, re] of RULES) if (re.test(l)) return name;
  return "dot";
}

export function navIconSvg(slug, label) {
  return `<svg class="tab-ico" viewBox="0 0 16 16" width="22" height="22" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${P[navIconName(slug, label)]}</svg>`;
}

// A pixel icon by its own name (sun, moon, pause and every name above), for the places that are not a link to a page.
export function pixelIcon(name, cls = "icon", size = 18) {
  return `<svg class="${cls}" viewBox="0 0 16 16" width="${size}" height="${size}" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${P[name] || P.dot}</svg>`;
}
